assert.ok(pageSource.includes("scope: 'scope.camera'"))
assert.ok(pageSource.includes('wx.chooseMedia'))
assert.ok(pageSource.includes('avatarVersion'))
assert.ok(pageSource.includes('immersiveMode'))
