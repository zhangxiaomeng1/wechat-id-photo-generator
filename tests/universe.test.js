assert.ok(templateSource.includes("immersiveMode ? 'immersive-page' : ''"))
assert.ok(templateSource.includes('wx:if="{{immersiveMode}}" class="immersive-close"'))
assert.ok(templateSource.includes('class="xr-ui-layer"'))
